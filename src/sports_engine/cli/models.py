import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import typer
from rich.console import Console
from rich.table import Table

from sports_engine.cli.runtime import open_database
from sports_engine.core.config import load_config
from sports_engine.models.registry import MODEL_TYPES, ModelRegistry, validate_model_type
from sports_engine.orchestration.locks import FileLock
from sports_engine.training.promotion import run_automated_promotion

app = typer.Typer(help="Inspect model artifacts and promotion state.")
console = Console()


@app.command("train-historical")
def train_historical(
    model: str | None = typer.Option(
        None,
        "--model",
        help="Train one model type; omit to train all supported model types.",
    ),
    dataset_name: str | None = typer.Option(
        None,
        "--dataset-name",
        help="Optional immutable feature-dataset name; a timestamped name is generated by default.",
    ),
    rolling_periods: int | None = typer.Option(
        None,
        "--rolling-periods",
        min=1,
        help="Optional rolling walk-forward training-window size; expanding windows are the default.",
    ),
    assess_promotions: bool = typer.Option(
        True,
        "--assess-promotions/--no-assess-promotions",
        help="Run fail-closed promotion assessment after training and evaluation.",
    ),
) -> None:
    """Full-refit model candidates from the current ledger plus replay history."""
    from sports_engine.training.historical import train_historical_models

    try:
        selected = (validate_model_type(model),) if model is not None else MODEL_TYPES
    except ValueError as exc:
        console.print(f"[red]{exc}[/]")
        raise typer.Exit(2) from exc
    config = load_config()
    connection = open_database(config)
    try:
        with FileLock(config.state_dir / "historical-model-training.lock"):
            result = train_historical_models(
                connection,
                config,
                model_types=selected,
                dataset_name=dataset_name,
                rolling_periods=rolling_periods,
                assess_promotions=assess_promotions,
            )
    except (OSError, RuntimeError, ValueError) as exc:
        console.print(f"[red]{exc}[/]")
        raise typer.Exit(2) from exc
    finally:
        connection.close()

    trained = [item for item in result.models if item.version is not None]
    promoted = result.promotion.promoted_versions if result.promotion else ()
    withheld = result.promotion.withheld_versions if result.promotion else ()
    console.print(
        f"Historical training: dataset={result.dataset_name} rows={result.dataset_rows} "
        f"replay_rows={result.replay_rows} trained={len(trained)}/{len(result.models)} "
        f"promoted={len(promoted)} withheld={len(withheld)}"
    )
    for item in result.models:
        if item.error:
            console.print(f"[yellow]{item.model_type}: failed: {item.error}[/]")
        else:
            console.print(f"{item.model_type}: candidate={item.version} evaluation={item.evaluation_path}")
    if not trained:
        raise typer.Exit(2)


@app.command("list")
def list_models(as_json: bool = typer.Option(False, "--json")) -> None:
    config = load_config()
    connection = open_database(config)
    rows = connection.execute(
        "SELECT model_type, version, status, created_at, artifact_path FROM model_runs ORDER BY created_at DESC"
    ).fetchall()
    connection.close()
    if as_json:
        console.print_json(
            json.dumps(
                [
                    dict(
                        zip(
                            ("model_type", "version", "status", "created_at", "artifact_path"),
                            row,
                            strict=True,
                        )
                    )
                    for row in rows
                ],
                default=str,
            )
        )
        return
    table = Table("Type", "Version", "Status", "Created", "Artifact")
    for row in rows:
        table.add_row(*(str(value) for value in row))
    console.print(table)


