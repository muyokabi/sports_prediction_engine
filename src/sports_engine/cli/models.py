@app.command("assess-promotions")
def assess_promotions(as_json: bool = typer.Option(False, "--json")) -> None:
    """Run the same fail-closed promotion cycle used by the principal workflow."""
    config = load_config()
    connection = open_database(config)
    try:
        result = run_automated_promotion(connection, config)
    finally:
        connection.close()
    payload = {
        "assessed": list(result.assessed_versions),
        "promoted": list(result.promoted_versions),
        "withheld": list(result.withheld_versions),
        "assessments": [
            {
                "version": item.version,
                "market_family": item.market_family,
                "state": item.state,
                "reasons": list(item.reasons),
            }
            for item in result.assessments
        ],
    }
    if as_json:
        console.print_json(json.dumps(payload))
        return
    console.print(
        f"Promotion assessment: assessed={len(result.assessed_versions)} "
        f"promoted={len(result.promoted_versions)} withheld={len(result.withheld_versions)}"
    )
    for item in result.assessments:
        console.print(f"{item.version}: {item.state}; {', '.join(item.reasons) or 'all gates passed'}")


@app.command("promote")
def promote(version: str = typer.Argument(..., help="Candidate model version.")) -> None:
    config = load_config()
    connection = open_database(config)
    try:
        result = run_automated_promotion(connection, config, versions=(version,))
        if version not in result.promoted_versions:
            assessment = next((item for item in result.assessments if item.version == version), None)
            reasons = ", ".join(assessment.reasons) if assessment else "candidate not found or not eligible"
            raise ValueError(f"Automated governance withheld {version!r}: {reasons}")
    except (OSError, RuntimeError, ValueError) as exc:
        console.print(f"[red]{exc}[/]")
        raise typer.Exit(2) from exc
    finally:
        connection.close()
    console.print(f"Promoted [bold]{version}[/] to its validated market-family champion role.")


@app.command("reject")
def reject(version: str = typer.Argument(..., help="Candidate model version.")) -> None:
    config = load_config()
    connection = open_database(config)
    try:
        ModelRegistry(connection).reject(version)
    except ValueError as exc:
        console.print(f"[red]{exc}[/]")
        raise typer.Exit(2) from exc
    finally:
        connection.close()
    console.print(f"Rejected candidate [bold]{version}[/].")


@app.command("reliability")
def reliability(as_json: bool = typer.Option(False, "--json")) -> None:
    config = load_config()
    connection = open_database(config)
    row = connection.execute(
        "SELECT version, training_start, training_end, metrics, calibration_method, "
        "training_dataset_hash, artifact_path, model_type, created_at FROM model_runs "
        "WHERE status='champion' ORDER BY created_at DESC LIMIT 1"
    ).fetchone()
    connection.close()
    if not row:
        console.print("[red]No champion model is registered.[/]")
        raise typer.Exit(2)
    metrics = row[3] if isinstance(row[3], dict) else json.loads(row[3])
    manifest_path = Path(row[6]).with_suffix(Path(row[6]).suffix + ".json")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.is_file() else {}
    reports = []
    for path in (config.artifacts_dir / "evaluation").glob(f"{row[7]}-{str(row[5])[:12]}-*.json"):
        reports.append(json.loads(path.read_text(encoding="utf-8")))
    latest_report: dict[str, Any] = max(reports, key=lambda item: item.get("created_at", ""), default={})
    payload = {
        "model_version": row[0],
        "training_start": row[1],
        "training_end": row[2],
        "training_fixtures": metrics.get("train_rows"),
        "validation_fixtures": metrics.get("validation_rows"),
        "test_fixtures": metrics.get("test_rows"),
        "log_loss": metrics.get("log_loss"),
        "brier": metrics.get("brier"),
        "rps": metrics.get("rps"),
        "ece": metrics.get("expected_calibration_error"),
        "calibration": row[4] or "none",
        "bookmaker_benchmark": "available" if metrics.get("bookmaker_baseline") else "unavailable",
        "walk_forward_periods": (latest_report.get("aggregate_metrics") or {}).get("folds"),
        "age_days": (datetime.now(UTC) - row[8]).total_seconds() / 86_400,
        "feature_dataset_hash": row[5],
        "leakage_audit": manifest.get("leakage_audit", "unverified"),
    }
    if as_json:
        console.print_json(json.dumps(payload, default=str))
        return
    table = Table("Measure", "Value")
    for key, value in payload.items():
        table.add_row(key.replace("_", " ").title(), str(value))
    console.print(table)
