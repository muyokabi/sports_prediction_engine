CREATE TABLE competition_discoveries (
    discovery_id UUID PRIMARY KEY,
    provider VARCHAR NOT NULL,
    provider_competition_id BIGINT NOT NULL,
    provider_season INTEGER NOT NULL,
    competition_season_id UUID REFERENCES competition_seasons(competition_season_id),
    name VARCHAR NOT NULL,
    country VARCHAR,
    competition_type VARCHAR,
    universe_state VARCHAR NOT NULL,
    fixture_count INTEGER,
    completed_fixture_count INTEGER,
    future_fixture_count INTEGER,
    coverage JSON NOT NULL,
    data_quality_score DOUBLE NOT NULL,
    market_quality_score DOUBLE NOT NULL,
    sample_value_score DOUBLE NOT NULL,
    operational_cost_score DOUBLE NOT NULL,
    suitability_score DOUBLE NOT NULL,
    exclusion_reasons JSON NOT NULL,
    expected_bootstrap_requests INTEGER,
    source_raw_path VARCHAR,
    discovered_at TIMESTAMPTZ NOT NULL,
    UNIQUE (provider, provider_competition_id, provider_season),
    CHECK (provider = 'api_football'),
    CHECK (universe_state IN ('DISCOVERED','OBSERVATION','ACTIONABLE','SUSPENDED','REJECTED'))
);
